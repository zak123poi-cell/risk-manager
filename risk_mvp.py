"""
MVP: Риск-калькулятор для оптовой торговли в условиях войны / форс-мажоров.

Запуск:
    streamlit run risk_mvp.py

Логика:
- Пользователь добавляет один или несколько складов (регион, статус аренды,
  товар, сроки оборачиваемости, наценка).
- Приложение считает базовый сценарий (без потерь): капитал, аренду, прибыль.
- Пользователь может смоделировать потерю одного или нескольких складов
  (например, попадание ракеты) и увидеть итоговый баланс сети.
- Отдельно считается итоговый % риска сети на основе региональных
  коэффициентов и времени, в течение которого капитал "под угрозой".
"""

import streamlit as st
import pandas as pd
from datetime import date

# ──────────────────────────────────────────────────────────────────────────
# 1. СПРАВОЧНИК РЕГИОНОВ И ИХ БАЗОВЫХ КОЭФФИЦИЕНТОВ РИСКА (0.1–1.0)
#    Чем выше значение — тем выше вероятность форс-мажора (обстрел,
#    оккупация, логистический коллапс и т.д.). Значения условные,
#    их можно и нужно калибровать под свой опыт.
# ──────────────────────────────────────────────────────────────────────────
REGION_RISK = {
    "Западная Украина (тыл)": 0.15,
    "Центральная Украина": 0.30,
    "Киев и область": 0.40,
    "Северная Украина (приграничье)": 0.55,
    "Южная Украина / Одесская область": 0.55,
    "Восточная Украина (прифронтовая зона)": 0.85,
    "Прифронтовая линия / серая зона": 1.00,
}

# Нормировочный период (в днях), после которого временной риск
# считается максимальным (1.0). Настраивается под вашу оборачиваемость.
TIME_RISK_NORMALIZATION_DAYS = 180

# Вес региональной составляющей и временной составляющей в итоговом риске склада
REGION_WEIGHT = 0.7
TIME_WEIGHT = 0.3


def calc_time_risk(days_at_risk: int) -> float:
    """Риск растёт с увеличением срока хранения товара на складе,
    капитал дольше находится "под угрозой". Ограничен сверху 1.0."""
    if days_at_risk <= 0:
        return 0.0
    return min(1.0, days_at_risk / TIME_RISK_NORMALIZATION_DAYS)


def calc_combined_risk(region_risk: float, days_at_risk: int) -> float:
    """Комбинированный риск склада: региональный + временной, взвешенные."""
    time_risk = calc_time_risk(days_at_risk)
    return REGION_WEIGHT * region_risk + TIME_WEIGHT * time_risk


# ──────────────────────────────────────────────────────────────────────────
# 2. ИНИЦИАЛИЗАЦИЯ СОСТОЯНИЯ (список складов хранится в session_state,
#    чтобы данные не пропадали между перерисовками интерфейса)
# ──────────────────────────────────────────────────────────────────────────
if "warehouses" not in st.session_state:
    st.session_state.warehouses = []  # список словарей-складов

st.set_page_config(page_title="Риск-калькулятор опта", layout="wide")
st.title("📦 Риск-калькулятор оптовой торговли в условиях форс-мажора")
st.caption(
    "Оцените капитал, ожидаемую прибыль и устойчивость сети складов "
    "к потере одной или нескольких точек."
)

# ──────────────────────────────────────────────────────────────────────────
# 3. САЙДБАР: ФОРМА ДОБАВЛЕНИЯ СКЛАДА
# ──────────────────────────────────────────────────────────────────────────
st.sidebar.header("➕ Добавить склад")

with st.sidebar.form("add_warehouse_form", clear_on_submit=True):
    wh_name = st.text_input("Название / ID склада", placeholder="Например: Склад №1 (Ровно)")

    region = st.selectbox("Регион (влияет на коэффициент риска)", list(REGION_RISK.keys()))
    region_risk_value = REGION_RISK[region]
    st.caption(f"Коэффициент риска региона: **{region_risk_value:.2f}**")

    ownership = st.radio("Статус склада", ["В аренде", "Собственный"], horizontal=True)
    fixed_cost = st.number_input(
        "Фикс. стоимость аренды/содержания за период ($)",
        min_value=0.0, value=0.0, step=50.0,
    )

    st.markdown("**Товар на складе**")
    unit_price = st.number_input("Закупочная цена за единицу ($)", min_value=0.0, value=10.0, step=1.0)
    quantity = st.number_input("Количество единиц товара", min_value=0, value=100, step=10)

    st.markdown("**Таймлайн оборачиваемости**")
    col_d1, col_d2 = st.columns(2)
    with col_d1:
        arrival_date = st.date_input("Дата поступления (закупки)", value=date.today())
    with col_d2:
        sale_date = st.date_input("Ожидаемая дата продажи (отгрузки)")

    markup_pct = st.slider("Ожидаемая наценка (%)", min_value=0, max_value=300, value=30)

    submitted = st.form_submit_button("Добавить склад")

    if submitted:
        if not wh_name:
            st.sidebar.error("Укажите название склада.")
        elif sale_date < arrival_date:
            st.sidebar.error("Дата продажи не может быть раньше даты поступления.")
        else:
            days_at_risk = (sale_date - arrival_date).days
            st.session_state.warehouses.append({
                "Название": wh_name,
                "Регион": region,
                "Риск региона": region_risk_value,
                "Статус": ownership,
                "Аренда/содержание ($)": fixed_cost,
                "Цена за ед. ($)": unit_price,
                "Кол-во": quantity,
                "Дата поступления": arrival_date,
                "Дата продажи": sale_date,
                "Дней под риском": days_at_risk,
                "Наценка (%)": markup_pct,
            })
            st.sidebar.success(f"Склад «{wh_name}» добавлен.")

if st.session_state.warehouses:
    if st.sidebar.button("🗑️ Очистить все склады"):
        st.session_state.warehouses = []
        st.rerun()

# ──────────────────────────────────────────────────────────────────────────
# 4. ЕСЛИ СКЛАДОВ НЕТ — ЗАГЛУШКА
# ──────────────────────────────────────────────────────────────────────────
if not st.session_state.warehouses:
    st.info("Добавьте хотя бы один склад через панель слева, чтобы увидеть расчёты.")
    st.stop()

# ──────────────────────────────────────────────────────────────────────────
# 5. РАСЧЁТНЫЙ СЛОЙ: ПОСКЛАДСКИЕ МЕТРИКИ
# ──────────────────────────────────────────────────────────────────────────
rows = []
for wh in st.session_state.warehouses:
    capital = wh["Цена за ед. ($)"] * wh["Кол-во"]              # стоимость товара
    margin_profit = capital * (wh["Наценка (%)"] / 100.0)       # чистая маржа (без учёта аренды)
    net_profit_after_lease = margin_profit - wh["Аренда/содержание ($)"]
    combined_risk = calc_combined_risk(wh["Риск региона"], wh["Дней под риском"])

    rows.append({
        **wh,
        "Капитал ($)": capital,
        "Маржа ($)": margin_profit,
        "Прибыль после аренды ($)": net_profit_after_lease,
        "Общий риск склада": round(combined_risk, 3),
    })

df = pd.DataFrame(rows)

st.subheader("📋 Сводная таблица складов")
st.dataframe(
    df[[
        "Название", "Регион", "Статус", "Кол-во", "Капитал ($)",
        "Аренда/содержание ($)", "Наценка (%)", "Дней под риском", "Общий риск склада",
    ]],
    use_container_width=True,
)

# ──────────────────────────────────────────────────────────────────────────
# 6. БАЗОВЫЙ СЦЕНАРИЙ (БЕЗ ПОТЕРЬ)
# ──────────────────────────────────────────────────────────────────────────
total_capital = df["Капитал ($)"].sum()
total_lease = df["Аренда/содержание ($)"].sum()
total_margin = df["Маржа ($)"].sum()
expected_profit_base = total_margin - total_lease

# Итоговый риск сети — средневзвешенное по капиталу (крупные склады весомее)
if total_capital > 0:
    network_risk = (df["Общий риск склада"] * df["Капитал ($)"]).sum() / total_capital
else:
    network_risk = 0.0

st.subheader("📊 Базовый сценарий (идеальные условия)")
c1, c2, c3, c4 = st.columns(4)
c1.metric("Общий капитал (товар)", f"${total_capital:,.0f}")
c2.metric("Аренда/содержание, всего", f"${total_lease:,.0f}")
c3.metric("Ожидаемая прибыль (база)", f"${expected_profit_base:,.0f}")
c4.metric("Итоговый риск сети", f"{network_risk * 100:.1f}%")

with st.expander("Как считается риск и от чего он зависит"):
    st.markdown(f"""
- **Региональный риск** — фиксированный коэффициент склада (0.1–1.0), заданный в справочнике регионов.
- **Временной риск** — растёт с числом дней между закупкой и продажей: чем дольше товар лежит на складе,
  тем дольше капитал "под угрозой". Достигает максимума (1.0) при {TIME_RISK_NORMALIZATION_DAYS} днях хранения.
- **Итоговый риск склада** = {REGION_WEIGHT:.0%} × региональный риск + {TIME_WEIGHT:.0%} × временной риск.
- **Риск сети** — средневзвешенное значение риска складов, взвешенное по капиталу
  (склад с большим товарным запасом сильнее влияет на общий риск).
""")

st.divider()

# ──────────────────────────────────────────────────────────────────────────
# 7. СИМУЛЯЦИЯ ФОРС-МАЖОРА (СТРЕСС-ТЕСТ)
# ──────────────────────────────────────────────────────────────────────────
st.subheader("🎯 Симуляция потерь (стресс-тест)")
st.caption(
    "Выберите один или несколько складов, чтобы смоделировать их полное "
    "уничтожение (например, попадание ракеты). Если ничего не выбрано — "
    "показан базовый расчёт без потерь."
)

destroyed_names = st.multiselect(
    "Склады для симуляции уничтожения",
    options=df["Название"].tolist(),
    default=[],
)

if destroyed_names:
    destroyed_df = df[df["Название"].isin(destroyed_names)]
    survivors_df = df[~df["Название"].isin(destroyed_names)]

    # Убыток: 100% стоимости товара на уничтоженных складах
    lost_capital = destroyed_df["Капитал ($)"].sum()
    # Фиксированные убытки: аренда/содержание уничтоженных складов уже оплачена
    lost_fixed_costs = destroyed_df["Аренда/содержание ($)"].sum()
    total_loss = lost_capital + lost_fixed_costs

    # Прибыль только с уцелевших складов (маржа минус их собственная аренда)
    survivors_margin = survivors_df["Маржа ($)"].sum()
    survivors_lease = survivors_df["Аренда/содержание ($)"].sum()
    survivors_profit = survivors_margin - survivors_lease

    # Итоговый баланс сети при данном сценарии
    final_balance = survivors_profit - total_loss

    st.markdown("#### Результат симуляции")
    s1, s2, s3 = st.columns(3)
    s1.metric("Потери при сценарии", f"-${total_loss:,.0f}",
              help="Стоимость уничтоженного товара + оплаченная аренда уничтоженных складов")
    s2.metric("Прибыль с уцелевших складов", f"${survivors_profit:,.0f}")
    s3.metric(
        "Итоговый баланс",
        f"${final_balance:,.0f}",
        delta=f"{'В плюсе' if final_balance > 0 else 'В минусе' if final_balance < 0 else 'В нуле'}",
        delta_color="normal" if final_balance >= 0 else "inverse",
    )

    st.markdown("#### Вердикт")
    if final_balance > 0:
        st.success(
            f"✅ Система устойчива: прибыль с уцелевших складов (${survivors_profit:,.0f}) "
            f"перекрывает потерю выбранных точек (-${total_loss:,.0f}). "
            f"Итоговый запас прочности: ${final_balance:,.0f}."
        )
    elif final_balance == 0:
        st.warning("⚖️ Баланс ровно в нуле: прибыль уцелевших складов точно покрывает убытки.")
    else:
        st.error(
            f"⚠️ Внимание: при потере складов {', '.join(destroyed_names)} "
            f"вы уходите в минус на ${abs(final_balance):,.0f}. "
            f"Диверсификация или объём резервов недостаточны для этого сценария."
        )

    with st.expander("Детали уничтоженных складов"):
        st.dataframe(
            destroyed_df[["Название", "Регион", "Капитал ($)", "Аренда/содержание ($)"]],
            use_container_width=True,
        )
    with st.expander("Детали уцелевших складов"):
        st.dataframe(
            survivors_df[["Название", "Регион", "Капитал ($)", "Маржа ($)", "Аренда/содержание ($)"]],
            use_container_width=True,
        )
else:
    st.info(
        "Ничего не выбрано — отображается базовый расчёт без потерь "
        "(см. блок «Базовый сценарий» выше)."
    )

st.divider()
st.caption(
    "MVP для внутреннего использования. Коэффициенты регионов и нормировку "
    "временного риска рекомендуется откалибровать под собственную статистику потерь."
)
